import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { orientation, questionCards } from "../site/js/summary.js";

// A recording DOM checks renderer structure and event wiring without claiming layout,
// native disclosure behavior or browser accessibility verification (tests/browser.mjs).
class RecordedNode extends EventTarget {
  constructor(tag = null, text = "") {
    super();
    this.tag = tag;
    this.text = text;
    this.children = [];
    this.attributes = new Map();
    this.open = false;
    this.isConnected = true;
  }
  append(node) { this.children.push(node); }
  setAttribute(name, value) {
    this.attributes.set(name, value);
    if (name === "open") this.open = true;
  }
  get textContent() { return this.text + this.children.map((child) => child.textContent).join(""); }
  querySelector(tag) { return descendants(this).find((node) => node.tag === tag) ?? null; }
  focus(options) { document.activeElement = this; this.focusOptions = options; }
  scrollIntoView(options) { this.scrollOptions = options; }
}
const descendants = (node) => node.children.flatMap((child) => [child, ...descendants(child)]);
const classIs = (name) => (node) => (node.attributes.get("class") ?? "").split(" ").includes(name);
const findId = (root, id) => descendants(root).find((node) => node.attributes.get("id") === id);
const nodes = (root, name) => descendants(root).filter(classIs(name));
const click = (node) => node.dispatchEvent(new Event("click"));
const snapshot = JSON.parse(readFileSync(new URL("../model/results/summary/summary-zcg.json", import.meta.url), "utf8")).output;

function setup(t) {
  const oldNode = globalThis.Node;
  const oldDocument = globalThis.document;
  globalThis.Node = RecordedNode;
  globalThis.document = {
    activeElement: null,
    createElement: (tag) => new RecordedNode(tag),
    createTextNode: (text) => new RecordedNode(null, text),
  };
  t.after(() => {
    if (oldNode === undefined) delete globalThis.Node; else globalThis.Node = oldNode;
    if (oldDocument === undefined) delete globalThis.document; else globalThis.document = oldDocument;
  });
  const topic = structuredClone(snapshot);
  const keys = new Set();
  const collect = (value) => {
    if (value === null || typeof value !== "object") return;
    if (Array.isArray(value.cites)) value.cites.forEach((key) => keys.add(key));
    Object.values(value).forEach(collect);
  };
  collect(topic);
  const ids = [...new Set([...keys].map((key) => Number(key.split("/")[0])))];
  const opened = [];
  const view = {
    posts: new Map([...keys].map((key) => [key, { key, number: Number(key.split("/")[1]), maturity: 6, clean: null, own_text: "Original text" }])),
    threadOf: new Map([...keys].map((key) => [key, { id: Number(key.split("/")[0]), title: "Thread" }])),
    letterOf: new Map(ids.map((id, index) => [id, String.fromCharCode(65 + index)])),
    news: { points: ["p17"] }, transform: (text) => text,
    state: { open: { questions: new Set(), arguments: new Set() } },
    actions: {
      setOpen(kind, id, open) { if (open) view.state.open[kind].add(id); else view.state.open[kind].delete(id); },
      openPost(key) { opened.push(key); },
    },
  };
  return { topic, view, opened };
}

test("initial summary exposes six native disclosures, with all details inside their own cards", (t) => {
  const { topic, view } = setup(t);
  const root = questionCards(topic, view);
  assert.equal(nodes(root, "question-card").length, 6);
  assert.deepEqual(nodes(root, "question-card").map((card) => [card.tag, card.open, card.children[0].tag]), Array.from({ length: 6 }, () => ["details", false, "summary"]));
  assert.deepEqual(nodes(root, "question-description").map((node) => node.textContent), topic.issues.map((issue) => issue.description.text));
  assert.deepEqual(nodes(root, "question-arguments").map((node) => [node.tag, node.open]), Array.from({ length: 6 }, () => ["details", false]));
  assert.deepEqual(nodes(root, "points").flatMap((list) => list.children.map((li) => li.attributes.get("id"))), topic.issues.flatMap((issue) => issue.points.map((id) => `argument-${id}`)));
  assert.equal(nodes(root, "badge-new").length, 1);
  assert.equal(nodes(root, "analysis-disclosure")[0].textContent, "AI-generated analysis. These notes are generated by AI and have not been reviewed by a human. They may misinterpret a post or miss context. Active maintenance is not guaranteed.");
  assert.equal(nodes(root, "next-question").length, 5);
  assert.equal(orientation(topic, view).children.length, 3);
});

test("Next opens and focuses each next heading without closing other questions", (t) => {
  const { topic, view } = setup(t);
  view.state.open.questions.add("q1");
  const root = questionCards(topic, view);
  for (let i = 1; i < topic.issues.length; i++) {
    const previous = findId(root, `question-q${i}`);
    const next = findId(root, `question-q${i + 1}`);
    click(nodes(previous, "next-question")[0]);
    assert.equal(next.open, true);
    assert.equal(view.state.open.questions.has(`q${i + 1}`), true);
    assert.equal(document.activeElement, next.children[0]);
    assert.deepEqual(next.children[0].focusOptions, { preventScroll: true });
    assert.deepEqual(next.children[0].scrollOptions, { block: "start", behavior: "auto" });
    assert.equal(previous.open, true);
  }
});

test("related questions, sources and retained disclosure state use the existing actions", (t) => {
  const { topic, view, opened } = setup(t);
  let root = questionCards(topic, view);
  const first = findId(root, "question-q1");
  first.open = true;
  first.dispatchEvent(new Event("toggle"));
  const detail = nodes(first, "question-arguments")[0];
  detail.open = true;
  detail.dispatchEvent(new Event("toggle"));
  click(nodes(first, "related-questions")[0].children[1]);
  assert.equal(findId(root, "question-q3").open, true);
  click(nodes(first, "cite")[0]);
  assert.deepEqual(opened, [topic.issues[0].decision_at_stake.cites[0]]);
  root = questionCards(topic, view);
  assert.equal(findId(root, "question-q1").open, true);
  assert.equal(nodes(findId(root, "question-q1"), "question-arguments")[0].open, true);
  // A queued event from a detached old tree cannot overwrite current state.
  first.isConnected = false;
  first.open = false;
  first.dispatchEvent(new Event("toggle"));
  assert.equal(view.state.open.questions.has("q1"), true);
  const current = findId(root, "question-q1");
  current.open = false;
  current.dispatchEvent(new Event("toggle"));
  assert.equal(view.state.open.questions.has("q1"), false);
});

test("source-derived prose remains text and is passed through anonymous text transformation", (t) => {
  const { topic, view } = setup(t);
  const payload = '<img src=x onerror="alert(1)"> @alice';
  topic.issues[0].description.text = payload;
  topic.issues[0].positions_with_post_references[0].text = payload;
  view.transform = (text) => text.replaceAll("@alice", "@Participant 1");
  const root = questionCards(topic, view);
  assert.equal(descendants(root).some((node) => node.tag === "img" || node.tag === "script"), false);
  assert.equal(nodes(root, "question-description")[0].textContent, '<img src=x onerror="alert(1)"> @Participant 1');
  assert.equal(descendants(root).filter((node) => node.tag === null && node.text.includes("onerror")).length, 2);
});
